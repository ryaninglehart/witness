"""The review page, and the fact that it renders untrusted text.

Everything this page displays arrives from data: transcripts full of
transcriber markup, notes generated by models, free-text evaluator comments.
The page's entire privacy argument is that nothing leaves the machine, and a
page that executes text arriving in its own input has given that up before any
network call is involved.
"""

from __future__ import annotations

import json
from pathlib import Path

from witness.corpus import Consultation, Utterance
from witness.gate import Gate
from witness.grounding import Assertion, Slot
from witness.pipeline import Pipeline
from witness.viewer import _embed, _escape_text, export

HOSTILE = "</script><script>window.__PWNED__=1</script>"


def _consultation(text: str = HOSTILE) -> Consultation:
    return Consultation(
        consultation_id="day1_consultation01",
        utterances=[
            Utterance(speaker="patient", text=text, start_s=0.0, end_s=2.0),
            Utterance(
                speaker="patient",
                text="Cough for three days <UNIN/> and a <UNSURE>sore</UNSURE> throat",
                start_s=2.0,
                end_s=6.0,
            ),
        ],
        presenting_complaint="",
        clinician_note="Cough for three days. Sore throat.",
        highlights=[],
    )


class TestScriptEmbedding:
    def test_a_closing_script_tag_cannot_escape_the_block(self):
        # The HTML parser ends a script element at the first literal
        # `</script` in the byte stream, whatever the JSON quoting says.
        payload = _embed({"text": HOSTILE})
        assert "</script>" not in payload
        assert "<" not in payload
        assert ">" not in payload

    def test_the_payload_still_decodes_to_the_original_text(self):
        # Escaping that mangles the data would trade one defect for a quieter
        # one: a reviewer reading a transcript that is not what was said.
        assert json.loads(_embed({"text": HOSTILE}))["text"] == HOSTILE

    def test_transcriber_markup_survives_the_round_trip(self):
        # <UNIN/> marks a genuinely unintelligible span. Stripping it would
        # destroy provenance a reviewer needs.
        marked = "Cough <UNIN/> and <UNSURE>sore</UNSURE> throat & more"
        assert json.loads(_embed({"t": marked}))["t"] == marked

    def test_title_interpolation_is_escaped(self):
        assert _escape_text('a<b>&"c') == "a&lt;b&gt;&amp;&quot;c"


class TestExportedPage:
    def test_hostile_transcript_text_does_not_reach_the_markup(self, tmp_path: Path):
        cons = _consultation()
        run = Pipeline(gate=Gate()).run(cons, cons.clinician_note, "m1", publish=False)
        html = export(run, cons, tmp_path / "p.html").read_text()

        script_open = html.index("window.__WITNESS__")
        block_end = html.index("</script>", script_open)
        payload = html[script_open:block_end]
        assert "__PWNED__" not in payload or "\\u003c" in payload
        # The one thing that must be true: no executable tag was introduced by
        # the data. Every `<script` in the file is one the template wrote.
        assert html.count("<script>") == html.count("</script>") == 2

    def test_the_page_is_self_contained(self, tmp_path: Path):
        # A CDN dependency breaks the page offline, and in a tool arguing that
        # nothing leaves the machine, an outbound request on page load is the
        # wrong default.
        cons = _consultation("Cough for three days")
        run = Pipeline(gate=Gate()).run(cons, cons.clinician_note, "m1", publish=False)
        html = export(run, cons, tmp_path / "p.html").read_text()
        for scheme in ("http://", "https://", "//cdn", "<link", "src="):
            assert scheme not in html, f"page reaches outside itself: {scheme}"


def test_assertion_slots_render_without_a_grounding_span():
    # A claim the grader could not ground has no span, and the page must still
    # draw it -- that is the case a reviewer most needs to see.
    a = Assertion(index=0, text="Allergic to penicillin", slot=Slot.ALLERGY)
    assert a.slot.is_safety_critical


# -- browser verification -------------------------------------------------
#
# The tests above check the bytes. This one checks what a browser does with
# them, which is the actual claim: string assertions about escaping are a
# proxy, and WIT-012 was a case where the proxy would have looked fine while
# the page executed injected script. Skipped unless Playwright is installed,
# because a reviewer must be able to run the suite without it.

import pytest  # noqa: E402

playwright = pytest.importorskip("playwright.sync_api", reason="browser check is optional")


@pytest.fixture(scope="module")
def browser():
    import os

    exe = os.environ.get("CHROMIUM_PATH", "/opt/pw-browsers/chromium")
    if not os.path.exists(exe):
        pytest.skip("no chromium available")
    with playwright.sync_playwright() as p:
        b = p.chromium.launch(executable_path=exe)
        yield b
        b.close()


def _render(tmp_path: Path, text: str) -> Path:
    cons = _consultation(text)
    run = Pipeline(gate=Gate()).run(cons, cons.clinician_note, "m1", publish=False)
    return export(run, cons, tmp_path / "page.html")


def test_injected_script_does_not_execute_in_a_browser(browser, tmp_path: Path):
    path = _render(tmp_path, "</script><script>window.__PWNED__=1</script> and a cough")
    page = browser.new_page()
    errors: list[str] = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto(path.as_uri())
    page.wait_for_timeout(300)
    assert page.evaluate("typeof window.__PWNED__ === 'undefined'")
    assert errors == []
    assert page.locator(".utt").count() == 2
    page.close()


def test_the_page_still_works_after_escaping(browser, tmp_path: Path):
    # An escape that renders the page inert would pass the security test and
    # fail the reviewer, which is the trade this fix must not make.
    path = _render(tmp_path, "Cough for three days")
    page = browser.new_page()
    page.goto(path.as_uri())
    page.wait_for_timeout(300)
    assert page.locator(".claim").count() > 0
    page.locator(".claim").first.click()
    page.wait_for_timeout(200)
    assert page.locator(".utt.hit").count() >= 0  # click handler ran without error
    page.close()


def test_the_page_makes_no_network_requests(browser, tmp_path: Path):
    path = _render(tmp_path, "Cough for three days")
    page = browser.new_page()
    external: list[str] = []
    page.on("request", lambda r: None if r.url.startswith("file://") else external.append(r.url))
    page.goto(path.as_uri())
    page.wait_for_timeout(300)
    assert external == []
    page.close()
